"""Convert a fixed-width BDF font to a C table of Mac Roman glyphs (0x20-0xFF).

    python3 tools/bdf2c.py third_party/spleen/spleen-6x12.bdf > src/mac/hostfont.h

Used by the Font Manager outside macOS, for text in families the game does not provide
(menu titles, window titles, alerts)."""
import sys

def parse(path):
    glyphs, w, h, desc = {}, 0, 0, 0
    cur, bits = None, None
    for line in open(path, encoding='ascii', errors='replace'):
        f = line.split()
        if not f:
            continue
        if f[0] == 'FONTBOUNDINGBOX':
            w, h, desc = int(f[1]), int(f[2]), -int(f[4])
        elif f[0] == 'ENCODING':
            cur = int(f[1])
        elif f[0] == 'BITMAP':
            bits = []
        elif f[0] == 'ENDCHAR':
            glyphs[cur] = bits
            bits = None
        elif bits is not None:
            bits.append(int(f[0], 16))
    return glyphs, w, h, desc

def main():
    glyphs, w, h, desc = parse(sys.argv[1])
    assert w <= 8
    print('/* Generated by tools/bdf2c.py from %s (Spleen, BSD 2-Clause licence,' % sys.argv[1].split('/')[-1])
    print(' * Copyright (c) 2018-2026 Frederic Cambus; see third_party/spleen/LICENSE).')
    print(' * Mac Roman characters 0x20-0xFF, one byte per row, leftmost pixel in bit 7. */')
    print('#define HOSTFONT_W %d' % w)
    print('#define HOSTFONT_H %d' % h)
    print('#define HOSTFONT_DESCENT %d' % desc)
    print('static const uint8_t hostfont[224][HOSTFONT_H] = {')
    for c in range(0x20, 0x100):
        u = ord(bytes([c]).decode('mac_roman'))
        rows = glyphs.get(u) or glyphs.get(ord('?'))
        rows = (rows + [0] * h)[:h]
        print('    { %s },  /* 0x%02X */' % (', '.join('0x%02X' % r for r in rows), c))
    print('};')

main()
