#!/usr/bin/env python3
"""Make the check-build copy of the ported game sources.

  mkcheck.py <out dir>

Copies src/game/*.c (not gen/) to <out dir>, rewriting every call to a ported function
`Name(...)` into `chk_Name(...)`. The chk_ trampolines (generated by gen_port.py) push
the arguments like the original caller and enter the function through its 68k entry, so
the differential checker sees calls between ported functions too, not only calls coming
from original 68k code. Definitions and hand-written glue_* functions are left alone.
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
GAME = os.path.join(ROOT, 'src', 'game')

def main(out, prefix='chk_'):
    names = [n for n in open(os.path.join(GAME, 'gen', 'chk_names.txt')).read().split() if n]
    if not names:
        return
    call = re.compile(r'(?<![\w.>])(' + '|'.join(sorted(map(re.escape, names), key=len, reverse=True)) + r')(\s*\()')
    fndef = re.compile(r'^(?:static\s+)?(?:inline\s+)?[A-Za-z_][\w \t\*]*?\b([A-Za-z_]\w*)\s*\([^;]*$')
    os.makedirs(out, exist_ok=True)
    for fn in sorted(os.listdir(GAME)):
        if not fn.endswith('.c'):
            continue
        src = open(os.path.join(GAME, fn)).read().split('\n')
        res, cur, in_glue_macro = [], None, 0
        for line in src:
            # glue defined through a macro (PGLUE(Name, ..., Name(...)), ARGS_GLUE(Name)):
            # its calls must stay direct, like inside glue_* functions
            if in_glue_macro or re.match(r'^[A-Z_]*GLUE\s*\(', line):
                in_glue_macro += line.count('(') - line.count(')')
                if in_glue_macro < 0: in_glue_macro = 0
                res.append(line)
                continue
            if line and not line[0].isspace() and not line.startswith(('#', '/', '*', '}')):
                m = fndef.match(line)
                if m:
                    cur = m.group(1)
            if cur and cur.startswith('glue_'):
                res.append(line)
                continue
            # leave the definition's own name alone: `uint32_t Name(` at column 0
            d = re.match(r'^(uint32_t\s+)(\w+)(\s*\()', line)
            if d:
                res.append(d.group(0) + call.sub(prefix + r'\1\2', line[d.end():]))
            else:
                res.append(call.sub(prefix + r'\1\2', line))
        text = '\n'.join(res)
        text = '#include "gen/proto_chk.h"\n#line 1 "src/game/%s"\n' % fn + text
        dst = os.path.join(out, fn)
        if not os.path.exists(dst) or open(dst).read() != text:
            open(dst, 'w').write(text)

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else 'chk_')
