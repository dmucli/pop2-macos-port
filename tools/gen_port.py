#!/usr/bin/env python3
"""Generate the glue between ported C code and the original 68k code.

Inputs
  tools/fn_index.json      every function: name, segment, offset, jump-table slot, stack params
  tools/sig_overrides.json per-function corrections: {"Name": {"params": [[off,size],...]}}
  work/traps.json          (optional) Toolbox trap signatures for the C trap wrappers
  src/game/**/*.c          ported functions = non-static definitions `uint32_t Name(` of indexed names

Outputs (src/game/gen/)
  proto.h       prototypes for every function (uniform types: 2-byte -> int16_t, 4-byte -> uint32_t)
  glue.c        68k->C glue for ported functions, C->68k trampolines for the others, and the table
  traps_c.h     C wrappers for Toolbox traps (`_GetResource(...)`), routed through the trap dispatcher
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
GEN = os.path.join(ROOT, 'src', 'game', 'gen')

# Original names that collide with C library / runtime symbols get a trailing underscore.
RESERVED = {'main', 'strdup', 'dprintf', 'strnicmp', 'stricmp', 'memicmp', 'strrev', 'strupr', 'strlwr',
            'strset', 'strnset', 'memmove', 'memcpy', 'memset', 'strlen', 'strcpy', 'strcmp', 'printf',
            'sprintf', 'malloc', 'free', 'exit', 'abs', 'rand', 'srand', 'time', 'clock', 'signal', 'open',
            'close', 'read', 'write', 'remove', 'rename', 'random', 'index', 'select', 'stat', 'link'}

def load_index():
    idx = json.load(open(os.path.join(HERE, 'fn_index.json')))
    for f in idx:
        if f['name'] in RESERVED:
            f['name'] += '_'
    ov = {}
    ov_path = os.path.join(HERE, 'sig_overrides.json')
    if os.path.exists(ov_path):
        ov.update(json.load(open(ov_path)))
    ov_dir = os.path.join(HERE, 'sig_overrides')
    if os.path.isdir(ov_dir):
        for fn in sorted(os.listdir(ov_dir)):
            if fn.endswith('.json'):
                ov.update(json.load(open(os.path.join(ov_dir, fn))))
    for f in idx:
        o = ov.get(f['name'])
        if o and 'params' in o:
            f['params'] = [{'off': p[0], 'size': p[1]} for p in o['params']]
        if o and 'conv' in o:
            f['conv'] = o['conv']
        if o and 'ret' in o:
            f['ret_override'] = o['ret']
        f['params'] = sorted([p for p in f['params'] if 'off' in p], key=lambda p: p['off'])
    return idx

def ported_names(names):
    found = {}
    pat = re.compile(r'^uint32_t\s+([A-Za-z_]\w*)\s*\(', re.M)
    for d, _, files in os.walk(os.path.join(ROOT, 'src', 'game')):
        if os.path.basename(d) == 'gen':
            continue
        for fn in files:
            if fn.endswith('.c'):
                for m in pat.finditer(open(os.path.join(d, fn)).read()):
                    if m.group(1) in names:
                        found[m.group(1)] = os.path.relpath(os.path.join(d, fn), ROOT)
    return found

def ctype(size):
    return 'int16_t' if size <= 2 else 'uint32_t'

def plist(f, with_types=True):
    if not f['params']:
        return 'void' if with_types else ''
    return ', '.join((ctype(p['size']) + ' ' if with_types else '') + 'p%d' % p['off'] for p in f['params'])

def gen_functions(idx, ported):
    os.makedirs(GEN, exist_ok=True)
    h = ['/* Generated by tools/gen_port.py — do not edit. */', '#pragma once', '#include <stdint.h>', '',
         '/* One prototype per original function. Parameters are named by their stack offset',
         ' * (p4 = first argument). 2-byte values are int16_t, 4-byte values (longs, pointers',
         ' * as emulated addresses) are uint32_t. The return value is the full D0 register. */', '']
    for f in idx:
        h.append('uint32_t %s(%s);' % (f['name'], plist(f)))
    h.append('')
    h.append('enum {')
    for i, f in enumerate(idx):
        h.append('    FN_%s = %d,' % (f['name'], i))
    h.append('    FN_COUNT = %d' % len(idx))
    h.append('};')
    open(os.path.join(GEN, 'proto.h'), 'w').write('\n'.join(h) + '\n')

    c = ['/* Generated by tools/gen_port.py — do not edit. */', '#include "../port.h"', '#include "proto.h"', '']
    for i, f in enumerate(idx):
        args_read = []
        for p in f['params']:
            o = p['off'] - 4
            args_read.append('(int16_t)rd16(sp + %d)' % o if p['size'] <= 2 else 'rd32(sp + %d)' % o)
        if f.get('conv') == 'manual':
            # register-convention routine: the port supplies `void glue_Name(void)` itself
            c.append('void glue_%s(void);' % f['name'])
            continue
        if f['name'] in ported and f.get('conv') == 'pascal':
            # Pascal: args are popped by the callee; a result goes into the slot above them.
            span = max([p['off'] - 4 + (2 if p['size'] <= 2 else 4) for p in f['params']] or [0])
            rb = f.get('ret_override', f.get('ret', 0)) or 0
            store = ''
            if rb == 2 or rb == 1: store = ' wr16(sp + %d, (uint16_t)r);' % span
            elif rb >= 4: store = ' wr32(sp + %d, r);' % span
            c.append('static void glue_%s(void) { maddr sp = emu_sp(); uint32_t r = %s(%s);%s emu_set_sp(sp + %d); emu_set_d0(r); }'
                     % (f['name'], f['name'], ', '.join(args_read), store, span))
        elif f['name'] in ported:
            c.append('static void glue_%s(void) { maddr sp = emu_sp(); (void)sp; emu_set_d0(%s(%s)); }'
                     % (f['name'], f['name'], ', '.join(args_read)))
        else:
            span = max([p['off'] - 4 + (2 if p['size'] <= 2 else 4) for p in f['params']] or [0])
            span = (span + 1) & ~1
            pascal = f.get('conv') == 'pascal'
            rb = (f.get('ret_override', f.get('ret', 0)) or 0) if pascal else 0
            slot = (2 if rb in (1, 2) else 4) if rb else 0
            body = ['uint32_t %s(%s) {' % (f['name'], plist(f))]
            body.append('    maddr sp0 = emu_sp(), sp = sp0 - %d;' % (span + slot))
            for p in f['params']:
                o = p['off'] - 4
                body.append('    %s(sp + %d, (%s)p%d);' % ('wr16' if p['size'] <= 2 else 'wr32', o,
                                                         'uint16_t' if p['size'] <= 2 else 'uint32_t', p['off']))
            body.append('    emu_set_sp(sp);')
            body.append('    uint32_t r = call68_fn(%d);' % i)
            if slot == 2: body.append('    r = rd16(sp + %d);' % span)
            elif slot == 4: body.append('    r = rd32(sp + %d);' % span)
            body.append('    emu_set_sp(sp0);')
            body.append('    return r;')
            body.append('}')
            c.extend(body)
    c.append('')
    c.append('const FnInfo fn_info[FN_COUNT] = {')
    for f in idx:
        glue = 'glue_' + f['name'] if (f['name'] in ported or f.get('conv') == 'manual') else 'NULL'
        ret = f.get('ret', 4)
        if f.get('ret_override') is not None: ret = f['ret_override']
        c.append('    {"%s", %d, 0x%05x, %d, %s, %d},' % (f['name'], f['seg'], f['segoff'],
                                                       f['jt'] if f['jt'] else 0, glue, ret))
    c.append('};')
    open(os.path.join(GEN, 'glue.c'), 'w').write('\n'.join(c) + '\n')

def gen_traps(traps_json):
    t = json.load(open(traps_json))
    out = ['/* Generated by tools/gen_port.py from Multiversal Interfaces — do not edit.',
           ' * C wrappers for Toolbox traps. They marshal through the emulated stack/registers',
           ' * and the trap dispatcher, so ported code behaves exactly like the original call. */',
           '#pragma once', '#include "../port.h"', '']
    seen = set()

    def is_bool(ty):
        return ty in ('Boolean', 'BOOLEAN', 'bool')

    def emit(name, info, word, selector=None, loc=None):
        if name in seen or not re.fullmatch(r'[A-Za-z_]\w*', name):
            return
        seen.add(name)
        args = info.get('args') or []
        regbased = info.get('regbased')
        rs = info.get('retsize') or 0
        ret = info.get('return', 'void')
        params = []
        for i, a in enumerate(args):
            if a.get('register') and not str(a['register']).startswith(('A', 'D')):
                continue
            params.append(('uint32_t' if (a.get('stack') or 4) == 4 or a.get('register') else 'int16_t', 'a%d' % i, a))
        sig = ', '.join('%s %s' % (ty, nm) for ty, nm, _ in params) or 'void'
        body = []
        if regbased and not selector:
            body.append('    tb_begin();')
            for ty, nm, a in params:
                r = a.get('register')
                if r:
                    body.append('    cpu_set(R_%s, (uint32_t)%s);' % (r[:2], nm))
            body.append('    tb_trap(0x%04X);' % word)
            rr = info.get('returnreg') or 'D0'
            body.append('    uint32_t r = cpu_get(R_%s);' % rr[:2])
            body.append('    tb_end();')
            body.append('    return r;')
        else:
            body.append('    tb_begin();')
            if rs:
                body.append('    push%d(0);' % (16 if rs == 2 else 32))
            for ty, nm, a in params:
                if a.get('register'):
                    continue
                if is_bool(a.get('type', '')):
                    body.append('    push16(%s ? 0x0100 : 0);' % nm)
                elif ty == 'int16_t':
                    body.append('    push16((uint16_t)%s);' % nm)
                else:
                    body.append('    push32(%s);' % nm)
            if selector is not None:
                if loc == 'StackW':
                    body.append('    push16(0x%04X);' % (selector & 0xFFFF))
                elif loc == 'StackL':
                    body.append('    push32(0x%08X);' % selector)
                else:
                    body.append('    cpu_set(R_D0, 0x%08X);' % selector)
            for ty, nm, a in params:
                if a.get('register'):
                    body.append('    cpu_set(R_%s, (uint32_t)%s);' % (a['register'][:2], nm))
            body.append('    tb_trap(0x%04X);' % word)
            if rs == 2:
                body.append('    uint32_t r = pop16();' if not is_bool(ret) else '    uint32_t r = pop16() >> 8;')
            elif rs == 4:
                body.append('    uint32_t r = pop32();')
            else:
                body.append('    uint32_t r = cpu_get(R_D0);')
            body.append('    tb_end();')
            body.append('    return r;')
        out.append('static inline uint32_t _%s(%s) {' % (name, sig))
        out.extend(body)
        out.append('}')

    for k, v in sorted(t['traps'].items()):
        if v.get('dispatcher_root') or v.get('pop') is None and not v.get('regbased'):
            continue
        emit(v['name'], v, int(k, 16))
        # OS traps whose flag bits select variants (NewPtrClear = A31E, NewHandleSys = A522, ...)
        if v.get('variants'):
            base = int(k, 16)
            flags = {'Clear': 0x0200, 'Sys': 0x0400, 'SysClear': 0x0600}
            for var in v['variants']:
                if var == v['name']: continue
                suffix = var[len(v['name']):] if var.startswith(v['name']) else None
                if suffix in flags:
                    emit(var, v, base | flags[suffix])
    for v in t['variants']:
        emit(v['name'], v, v['trap'], v['selector'], v['loc'])
    open(os.path.join(GEN, 'traps_c.h'), 'w').write('\n'.join(out) + '\n')

def main():
    idx = load_index()
    names = {f['name'] for f in idx}
    ported = ported_names(names)
    gen_functions(idx, ported)
    tj = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, '..', 'work', 'traps.json')
    if os.path.exists(tj):
        gen_traps(tj)
    elif not os.path.exists(os.path.join(GEN, 'traps_c.h')):
        sys.exit('traps.json not found: pass its path')
    print('functions: %d, ported: %d' % (len(idx), len(ported)))

if __name__ == '__main__':
    main()
